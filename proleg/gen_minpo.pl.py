def parse_articles(text: str):
    lines = text.splitlines()
    articles = []
    section = ""
    i = 0
    while i < len(lines):
        line = lines[i]
        top = TOP.match(line)
        if top and not line.startswith("###"):
            section = top.group(1)
            i += 1
            continue
        m = ARTICLE.match(line)
        if m:
            art, title = m.group(1), m.group(2) or ""
            body: list[str] = []
            i += 1
            while i < len(lines) and not re.match(r"^#{2,6}\s+", lines[i]):
                body.append(lines[i])
                i += 1
            articles.append((section, art, title, "\n".join(body).strip()))
            continue
        i += 1
    return articles


def summarize(body: str, limit: int = 120) -> str:
    flat = re.sub(r"\s+", " ", body).strip()
    flat = re.sub(r"<[^>]+>", "", flat)
    if len(flat) <= limit:
        return flat
    return flat[: limit - 1] + "…"


def render(articles) -> str:
    out = [HEADER]
    current_section = None
    for section, art, title, body in articles:
        if section != current_section:
            out.append(f"\n% ===== {section} =====\n")
            current_section = section
        label = f"{art}（{title}）" if title else art
        out.append(f"% ========== {label} ==========")
        summary = summarize(body)
        if summary:
            out.append(f"% 条文要旨: {summary}")
        # 附則の「第一条」等に本文ルールを誤適用しない
        in_main = section.startswith(("第一編", "第二編", "第三編", "第四編", "第五編"))
        if in_main and art in RULES:
            out.append(RULES[art].rstrip())
            out.append("")
        else:
            out.append("% TODO: 要件事実論に基づきルールを記述")
            out.append("")
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    articles = parse_articles(MD.read_text(encoding="utf-8"))
    text = render(articles)
    OUT.write_text(text, encoding="utf-8")
    n_rules = sum(
        1
        for section, art, _, _ in articles
        if section.startswith(("第一編", "第二編", "第三編", "第四編", "第五編")) and art in RULES
    )
    print(f"wrote {OUT} ({len(articles)} articles, {n_rules} with substantive rules)")
    return 0


